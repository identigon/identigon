#!/bin/sh
# doc-kit-index-decisions - generate decisions.md index for docs/decisions.
#
# Usage: sh tools/doc-kit-index-decisions.sh [output-file] [decisions-dir]
#
# Defaults: output-file   <decisions-dir>.md
#           decisions-dir docs/decisions

set -eu

# Keep the index order and table comparison identical on every runner.
LC_ALL=C
export LC_ALL

DIR=${2:-docs/decisions}
OUT=${1:-${DIR}.md}

if [ ! -d "$DIR" ]; then
	echo "doc-kit-index-decisions: directory not found: $DIR" >&2
	exit 1
fi

rel_prefix="$(basename "$DIR")/"
case "$OUT" in
	*/README.md|"$DIR"/*) rel_prefix="" ;;
esac

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT HUP INT TERM

awk -v rel_prefix="$rel_prefix" '
	function rep(char, count) {
		s = ""
		for (c = 0; c < count; c++) s = s char
		return s
	}
	function flush() {
		if (f == "" || skip) return
		total++
		order[total] = f
		file_base[f] = base
		file_num[f] = num
		file_status[f] = status
		file_date[f] = date
		file_deciders[f] = deciders
		file_title[f] = title
		file_confirm[f] = (confirm != "" ? confirm : "-")
	}
	FNR == 1 {
		flush()
		f = FILENAME
		base = f; sub(".*/", "", base)
		if (base ~ /^0000-/ || base == "README.md") { skip = 1; next }
		skip = 0
		status = ""; date = ""; deciders = ""; title = ""; num = ""; confirm = ""
		in_yaml = 0; in_confirm = 0
	}
	skip { next }
	FNR == 1 && /^---$/ { in_yaml = 1; next }
	in_yaml && /^---$/ { in_yaml = 0; next }
	in_yaml && /^status:/ {
		sub(/^status:[ \t]*"?/, ""); sub(/"?[ \t]*$/, ""); status = $0
	}
	in_yaml && /^date:/ {
		sub(/^date:[ \t]*"?/, ""); sub(/"?[ \t]*$/, ""); date = $0
	}
	in_yaml && /^decision-makers:/ {
		sub(/^decision-makers:[ \t]*"?/, ""); sub(/"?[ \t]*$/, ""); deciders = $0
	}
	!in_yaml && /^# [0-9]+/ {
		t = $0; sub(/^# [0-9]+\.[ \t]*/, "", t)
		title = t
		n = base; sub(/-.*/, "", n)
		num = n
	}
	!in_yaml && /^## Confirmation/ {
		in_confirm = 1; next
	}
	in_confirm && /^## / {
		in_confirm = 0
	}
	in_confirm && confirm == "" && $0 !~ /^[ \t]*$/ && $0 !~ /^<!--/ && $0 !~ /^{/ {
		c = $0; gsub(/`/, "", c)
		confirm = "`" c "`"
	}
	END {
		flush()

		# Compute column widths for in-force table
		w_rec = 6; w_date = 4; w_dec = 8; w_title = 8; w_conf = 12
		in_force = 0
		for (i = 1; i <= total; i++) {
			f = order[i]
			if (file_status[f] == "accepted") {
				in_force++
				l = length("[ADR-" file_num[f] "](" rel_prefix file_base[f] ")")
				if (l > w_rec) w_rec = l
				if (length(file_date[f]) > w_date) w_date = length(file_date[f])
				if (length(file_deciders[f]) > w_dec) w_dec = length(file_deciders[f])
				if (length(file_title[f]) > w_title) w_title = length(file_title[f])
				if (length(file_confirm[f]) > w_conf) w_conf = length(file_confirm[f])
			}
		}

		# Compute column widths for non-binding table
		w_nb_rec = 6; w_nb_stat = 6; w_nb_date = 4; w_nb_title = 8
		non_binding = 0
		for (i = 1; i <= total; i++) {
			f = order[i]
			if (file_status[f] != "accepted") {
				non_binding++
				l = length("[ADR-" file_num[f] "](" rel_prefix file_base[f] ")")
				if (l > w_nb_rec) w_nb_rec = l
				l_stat = length("`" file_status[f] "`")
				if (l_stat > w_nb_stat) w_nb_stat = l_stat
				if (length(file_date[f]) > w_nb_date) w_nb_date = length(file_date[f])
				if (length(file_title[f]) > w_nb_title) w_nb_title = length(file_title[f])
			}
		}

		print "<!-- Generated by tools/doc-kit-index-decisions.sh - do not edit by hand -->"
		print ""
		print "# Decision records"
		print ""
		print "Index of decision records. Only **accepted** records bind."
		print ""
		print "## In force"
		print ""
		printf "| %-*s | %-*s | %-*s | %-*s | %-*s |\n", w_rec, "Record", w_date, "Date", w_dec, "Deciders", w_title, "Question", w_conf, "Confirmation"
		printf "| %s | %s | %s | %s | %s |\n", rep("-", w_rec), rep("-", w_date), rep("-", w_dec), rep("-", w_title), rep("-", w_conf)
		if (in_force == 0) {
			printf "| %-*s | %-*s | %-*s | %-*s | %-*s |\n", w_rec, "_none_", w_date, "-", w_dec, "-", w_title, "-", w_conf, "-"
		} else {
			for (i = 1; i <= total; i++) {
				f = order[i]
				if (file_status[f] == "accepted") {
					rec = "[ADR-" file_num[f] "](" rel_prefix file_base[f] ")"
					printf "| %-*s | %-*s | %-*s | %-*s | %-*s |\n", w_rec, rec, w_date, file_date[f], w_dec, file_deciders[f], w_title, file_title[f], w_conf, file_confirm[f]
				}
			}
		}
		print ""
		print "## Non-binding"
		print ""
		printf "| %-*s | %-*s | %-*s | %-*s |\n", w_nb_rec, "Record", w_nb_stat, "Status", w_nb_date, "Date", w_nb_title, "Question"
		printf "| %s | %s | %s | %s |\n", rep("-", w_nb_rec), rep("-", w_nb_stat), rep("-", w_nb_date), rep("-", w_nb_title)
		if (non_binding == 0) {
			printf "| %-*s | %-*s | %-*s | %-*s |\n", w_nb_rec, "_none_", w_nb_stat, "-", w_nb_date, "-", w_nb_title, "-"
		} else {
			for (i = 1; i <= total; i++) {
				f = order[i]
				if (file_status[f] != "accepted") {
					rec = "[ADR-" file_num[f] "](" rel_prefix file_base[f] ")"
					stat = "`" file_status[f] "`"
					printf "| %-*s | %-*s | %-*s | %-*s |\n", w_nb_rec, rec, w_nb_stat, stat, w_nb_date, file_date[f], w_nb_title, file_title[f]
				}
			}
		}
	}
' "$DIR"/*.md > "$tmp"

mv "$tmp" "$OUT"
